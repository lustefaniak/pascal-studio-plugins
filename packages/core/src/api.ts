/**
 * Client for the local studio worker (the HTTP contract is in README.md).
 *
 * Everything that needs a filesystem or a third-party host lives there, not in
 * the browser: Pascal's node schema only accepts model URLs on localhost, the
 * IKEA endpoints send no CORS headers, and captures have to land as files in
 * the worker's shots directory. The worker is also what an agent talks to over
 * MCP, so
 * a shot rendered from the panel and one rendered from an agent go through the
 * exact same path.
 */

/**
 * Same port the old `assets-server.py` used, so model URLs already in the
 * scene keep resolving — the worker replaces that script rather than running
 * beside it. `window.__STUDIO_WORKER__` overrides it, which is how you point
 * the panel at a second worker while the usual one is busy.
 */
export const WORKER_ORIGIN =
  (globalThis as { __STUDIO_WORKER__?: string }).__STUDIO_WORKER__ ?? 'http://127.0.0.1:8899'

export type LibraryModel = {
  /** Path below its source directory, e.g. `ikea/pax-forsand-50214560.glb`. */
  path: string
  name: string
  /** Carries `?v=<mtime>`: a regenerated model is a different URL, which is
   *  the only thing the GLB loader's cache will treat as a new model. */
  url: string
  sizeBytes: number
  modifiedAt: number
  /** Bounding box in metres, [width, height, depth]; null when unreadable. */
  dimensions: [number, number, number] | null
  /** Correction that puts the model's own box around the node's origin, which is
   *  where Pascal draws `dimensions` from. Usually all zeros — but some IKEA
   *  models are authored off a bottom corner, and those stand where you dropped
   *  them while their box sits half a metre away, inside a wall. */
  offset: [number, number, number] | null
  source: string
  tags: string[]
  room: string
  notes: string
}

export type IkeaHit = {
  id: string
  name: string
  typeName: string
  measure: string
  thumbnail: string
  /** False when IKEA publishes no 3D model for the product — importing it would 404. */
  model: boolean
  /** `SPR` is a ready-made set (a wardrobe with doors), `ART` a single article (the frame). */
  itemType: string
  /** Finish, as IKEA names it: `white`, `white stained oak effect`. */
  color: string
  price: number | null
  pipUrl: string
  /** How many colours and sizes the product comes in; 0 means it stands alone. */
  variantCount: number
}

/** One colour/size the product also comes in. `options` is keyed by axis id (`colour`, `size`). */
export type IkeaVariant = {
  id: string
  name: string
  typeName: string
  measure: string
  color: string
  price: number | null
  thumbnail: string
  model: boolean
  /** True for the variant the details were opened on. */
  current: boolean
  options: Record<string, string>
}

/** A piece of a set, or an accessory sold to go with it (`quantity` 0 for the latter). */
export type IkeaPart = {
  id: string
  name: string
  typeName: string
  quantity: number
  thumbnail: string
  model: boolean
}

export type IkeaProduct = IkeaHit & {
  axes: { id: string; name: string; values: string[] }[]
  variants: IkeaVariant[]
  /** What a set is made of. Empty for a single article. */
  parts: IkeaPart[]
  related: { group: string; items: IkeaPart[] }[]
  cached?: boolean
}

export type ShotRequest = {
  /**
   * `export` asks for the scene as GLB instead of shots; the worker hands those
   * only to its own headless editor. Absent on shot requests.
   */
  kind?: 'export'
  /** Node ids to render; empty means every camera in the scene. */
  cameraIds: string[]
  width: number
  height: number
  requestId: string
}

async function call<T>(path: string, init?: RequestInit): Promise<T> {
  const response = await fetch(`${WORKER_ORIGIN}${path}`, {
    ...init,
    headers: { 'content-type': 'application/json', ...(init?.headers ?? {}) },
  })
  if (!response.ok) {
    throw new Error(`worker ${path}: ${response.status} ${await response.text()}`)
  }
  return (await response.json()) as T
}

export function listLibrary(): Promise<{
  models: LibraryModel[]
  directories: string[]
  fingerprint: string
}> {
  return call('/studio/library')
}

/**
 * Resolves when a watched directory changes — a long poll, not a timer, so a
 * model regenerated by a script appears in the panel a second later without
 * anyone reloading anything.
 */
export function watchLibrary(
  since: string,
  signal: AbortSignal,
): Promise<{ fingerprint: string; changed: boolean }> {
  return call(`/studio/library/watch?since=${encodeURIComponent(since)}`, { signal })
}

/** `cached` is true when the worker answered from disk rather than from IKEA. */
export function searchIkea(query: string): Promise<{ hits: IkeaHit[]; cached?: boolean }> {
  return call(`/studio/ikea/search?q=${encodeURIComponent(query)}`)
}

/**
 * Colours, sizes, set contents and accessories for one product.
 *
 * A search row is one finish in one size of something IKEA sells in a dozen,
 * and the fittings that go inside a frame never come back from a search at
 * all — this is where the rest of the range is.
 */
export function fetchIkeaProduct(id: string): Promise<IkeaProduct> {
  return call(`/studio/ikea/product?id=${encodeURIComponent(id)}`)
}

/**
 * A ceiling, not a level. `mini` is the light decimated model IKEA serves from
 * a predictable URL; `better` and `max` take the best the product page
 * publishes below that ceiling. Which levels exist varies per product, so both
 * fall back to `mini` rather than failing.
 */
export type IkeaQuality = 'mini' | 'better' | 'max'

/**
 * Downloads the product's GLB into the local library and returns it ready to
 * place. `level` says which quality actually landed — it is also the filename
 * suffix, so two levels of one product are two models.
 */
export function importIkea(
  id: string,
  name: string,
  quality: IkeaQuality,
): Promise<LibraryModel & { level: string }> {
  return call('/studio/ikea/import', {
    method: 'POST',
    body: JSON.stringify({ id, name, quality }),
  })
}

/**
 * Long-poll for work queued by an agent. Resolves to `null` when the poll times
 * out with nothing pending, which is the normal case — the caller just asks
 * again, so an idle editor costs one open request rather than a busy loop.
 */
/**
 * True in the headless editor the worker starts for renders (`?studio-renderer=1`).
 * The worker hands jobs only to that tab while it runs, so ordinary tabs stop
 * competing for the queue with a stale copy of the graph.
 */
export function isHeadlessRenderer(): boolean {
  return (
    typeof window !== 'undefined' &&
    new URLSearchParams(window.location.search).has('studio-renderer')
  )
}

export async function nextShotRequest(signal: AbortSignal): Promise<ShotRequest | null> {
  const role = isHeadlessRenderer() ? '?role=headless' : ''
  const response = await fetch(`${WORKER_ORIGIN}/studio/commands${role}`, { signal })
  if (!response.ok) return null
  const body = (await response.json()) as { request: ShotRequest | null }
  return body.request
}

/** Hands a finished capture back to the worker, which writes it to disk. */
export async function postShot({
  requestId,
  name,
  blob,
  meta,
}: {
  requestId: string
  name: string
  blob: Blob
  meta: Record<string, unknown>
}): Promise<void> {
  await fetch(`${WORKER_ORIGIN}/studio/shots`, {
    method: 'POST',
    headers: {
      'content-type': blob.type || 'application/octet-stream',
      'x-studio-request': requestId,
      'x-studio-name': name,
      // Headers are latin-1 only, and shot names can carry accented letters.
      'x-studio-meta': encodeURIComponent(JSON.stringify(meta)),
    },
    body: blob,
  })
}

/** Reports that a queued request finished, so the agent's MCP call can return. */
/** Hands an exported scene to the worker, which keeps it for its API and renderers. */
export async function postSceneGlb(requestId: string, glb: Blob): Promise<void> {
  const response = await fetch(`${WORKER_ORIGIN}/studio/scene.glb`, {
    method: 'POST',
    headers: { 'content-type': 'model/gltf-binary', 'x-studio-request': requestId },
    body: glb,
  })
  if (!response.ok) throw new Error(`worker /studio/scene.glb: ${response.status}`)
}

export async function completeShotRequest(requestId: string, error?: string): Promise<void> {
  await fetch(`${WORKER_ORIGIN}/studio/commands/complete`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ requestId, error: error ?? null }),
  })
}
